"""地球与引力相关常数。长度单位一律 km，时间单位 s。"""

G = 6.674e-11          # 万有引力常量，m^3 kg^-1 s^-2
M_EARTH = 5.972e24     # 地球质量，kg

# 地球引力常数，换算到 km^3/s^2（1 m^3 = 1e-9 km^3）
MU = G * M_EARTH / 1e9

# WGS84 椭球：赤道半径（km）与扁率；轨道高度从赤道半径的球面量起
R_EARTH = 6378.137
FLATTENING = 1.0 / 298.257223563

